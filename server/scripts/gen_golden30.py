r = indicators.rsi(close)
line, sig, hist = indicators.macd(close)
bou, bol, w, pos, sq = indicators.bollinger_band(close)

adx, plus_di, minus_di = indicators.adx_di(high, low, close)

# Note: ADX, plus/minus DI are computed by core.indicators.adx_di
# which returns final scalar values; here we write them directly.
golden = {
    "rsi14": float(r[-1]),
    "macdLine": float(line[-1]),
    "macdSignal": float(sig[-1]),
    "macdHistNorm": float(hist[-1]),
    "adx14": float(adx),
    "plusDI": float(plus_di),
    "minusDI": float(minus_di),
    "bollingerUpper": float(bou),
    "bollingerLower": float(bol),
    "bollingerPosition": float(pos),
    "bollingerSqueeze": bool(sq),
    # Placeholder keys from previous format kept for backward compatibility
    "ema20": float(np.nan),
    "ema50": float(np.nan),
    "ema200": float(np.nan),
    "atr14pct": float(np.nan),
    "bollingerWidthPct": float(w),
    "obvSlope": float(np.nan),
    "volumeRatio520": float(np.nan),
    "deliveryPct5": float(np.nan),
    "divergenceBearish": False,
    "divergenceBullish": False,
    "structureState": "UP",
}
with open("tests/fixtures/golden/golden30.json", "w") as f:
    json.dump(golden, f, indent=2)
print("Regenerated golden30.json")
